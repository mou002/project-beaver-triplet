#define SHM_BERN_NAME "/bern_xproc_shm"

typedef struct {
    volatile uint8_t ready_v;        // victim has initialized
    volatile uint8_t exit_flag;      // attacker asks victim to quit
    volatile uint8_t trigger;        // attacker sets 1; victim clears to 0 when done
    volatile uint8_t keysel;         // 0 = known reference key, 1 = secret key
    uint8_t plaintext[16];           // attacker writes the input block
    uint8_t true_key[16];            // victim writes the SECRET key here -- VALIDATION
                                     // ONLY (attacker uses it only to score its guess,
                                     // never in the recovery itself)
    uint8_t _pad[64];
} BernShared;

