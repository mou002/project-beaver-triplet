// common_bern.h -- shared state + AES machinery for the multi-process (cross-process)
// Bernstein total-time attack. Victim runs AES-128 on a trigger; attacker times the
// trigger round-trip (which contains the victim's encryption) and runs the Bernstein
// analysis. Tables are victim-private (total-time doesn't probe them directly); the
// attacker's cache eviction thrashes the shared LLC so the victim's next encryption
// runs cold and its timing depends on key^plaintext, exactly as in the self-attack.
